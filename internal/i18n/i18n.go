func SetLanguage(lang string) {
	if _, ok := translations[lang]; ok {
		current = lang
	}
}

func T(key string) string {
	if msg, ok := translations[current][key]; ok {
		return msg
	}
	if msg, ok := translations["en"][key]; ok {
		return msg
	}
	return key
}
